/**
 * 「这一段是不是正在发生的画面」。
 *
 * 模型能读懂的语义判据在契约里（要求只选正在发生的瞬间），这里只守一个封闭集合：
 * 整段只有计划/回忆/推演/将来时，且没有任何当下动作动词，就不是可画的画面。
 * 实机反例：第 12 楼正文「回到书房，李斌点了一根烟，开始思索如何攻略小姨子，
 * 通过买奶茶这一点…」，插件画出了「她坐在客厅沙发上喝奶茶」——那不是这一楼发生的事。
 */
const PLAN_WORDS = /(思索|琢磨|盘算|打算|计划|盘算着|思来想去|回忆|回想起|记得|想起|如果|假如|要是|将来|以后|迟早|早晚|必须|需要|应该|最好|得先|一步一步|一步一步来|策略|攻略)/;

const ON_SCREEN_ACTION = /(走|跑|站|坐下|躺|趴|跪|蹲|伸|抓|握|按|压|推|拉开|拉过|扯|撩|掀|解开|扣上|穿上|脱下|褪下|抱|搂|亲|吻|舔|咬|吸|含|摸|抚|揉|捏|插|顶|抽送|撞|抖|喘|颤|闭|睁|扭头|低头|抬头|抬眼|挪|靠|贴|倚|踢|踩|递|接住|拿起|放下|举|甩|拍|打|捂|掩|挡|扶|拨|系上|整理|起身|俯身|弯腰|退后|后退)/;

/** 整段只有思虑/推演、没有任何当下动作时返回 true。 */
export function isNarratedOnly(segment: string): boolean {
  const text = (segment || '').trim();
  if (!text) return false;
  const hasAction = ON_SCREEN_ACTION.test(text);
  if (hasAction) return false;
  return PLAN_WORDS.test(text);
}
