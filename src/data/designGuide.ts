export interface DesignAudit {
  /** 逐条问题,空数组 = 通过。 */
  issues: string[];
  /** 语句是否足够具体(判定为"能画出轮廓")。 */
  ok: boolean;
}

const BAGU =
  /(?:严格遵循|符合.{0,16}(?:要求|规范|设定|世界观|审美)|根据.{0,20}(?:要求|规范|设定)|因为.{0,24}?(?:所以|因此)|整体而言|综上所述|在不违背.{0,24}的前提下|为了突出|旨在体现)/u;
const PRAISE = /(?:美丽动人|惊艳绝伦|令人移不开目光|独特魅力|宛若仙子|风华绝代|高贵优雅|提升整体气质|更加精致)/gu;
const CONCRETE =
  /(?:领|袖|裙|裤|摆|腰|襟|肩|袜|鞋|跟|缎|纱|绒|皮|绣|纹|褶|扣|带|珠|链|扣|金|银)/gu;

/**
 * 检查一段服装设计文字是否够"能画出来"。
 * 只做粗筛:太短、通篇套话、没有一个具体部件,都算不行。
 */
export function auditDesign(text: string): DesignAudit {
  const body = String(text ?? '').trim();
  const issues: string[] = [];
  const chars = [...body].length;
  if (chars < 40) issues.push('描述太短,撑不出轮廓');
  if (BAGU.test(body) && chars < 130) issues.push('偏"设计说明腔",缺具体部件');
  const praise = body.match(PRAISE)?.length ?? 0;
  const concrete = body.match(CONCRETE)?.length ?? 0;
  if (praise >= 2 && concrete < 2) issues.push('只有赞美词,没有可画细节');
  if (concrete < 3) issues.push('具体部件太少(领/袖/裙长/材质/鞋跟等)');
  return { issues, ok: !issues.length };
}
